"use client";

import Link from "next/link";
import { useState } from "react";
import { ArrowLeft, Mail, Send } from "lucide-react";
import { Alert } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import { Field, TextInput } from "@/components/ui/form";
import { api } from "@/lib/api";
import { getErrorMessage } from "@/lib/utils";

export function ForgotPasswordForm() {
  const [email, setEmail] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [sent, setSent] = useState(false);
  const [submitting, setSubmitting] = useState(false);

  const onSubmit = async (event: React.FormEvent) => {
    event.preventDefault();
    setError(null);
    if (!email.trim()) {
      setError("Enter the email address linked to your account.");
      return;
    }

    setSubmitting(true);
    try {
      await api.forgotPassword(email.trim());
      setSent(true);
    } catch (err) {
      setError(getErrorMessage(err, "Could not send the reset link"));
    } finally {
      setSubmitting(false);
    }
  };

  if (sent) {
    return (
      <div className="space-y-5">
        <Alert variant="success" title="Check your inbox">
          If an account exists for{" "}
          <span className="font-semibold">{email.trim()}</span>, a password
          reset link has been sent. The link expires in 15 minutes.
        </Alert>

        <div className="space-y-2.5">
          <Link
            href="/reset-password"
            className="flex h-11 items-center justify-center gap-2 rounded-xl bg-accent text-sm font-semibold text-white transition hover:bg-accent-strong dark:text-slate-950"
          >
            I have a reset token
          </Link>
          <button
            type="button"
            onClick={() => setSent(false)}
            className="flex h-10 w-full items-center justify-center gap-1.5 rounded-xl text-xs font-semibold text-muted transition hover:text-ink"
          >
            <ArrowLeft className="size-3.5" /> Try a different email
          </button>
        </div>

        <p className="text-[11px] leading-relaxed text-muted">
          Reset links generated by the API point to the backend. If yours opens a
          JSON response, copy the token from the address bar and paste it on the
          reset page.
        </p>
      </div>
    );
  }

  return (
    <form onSubmit={onSubmit} className="space-y-4" noValidate>
      {error ? (
        <Alert variant="error" title="Request failed">
          {error}
        </Alert>
      ) : null}

      <Field
        label="Email address"
        htmlFor="email"
        required
        hint="We will send a secure, single-use reset link if the account exists."
      >
        <TextInput
          id="email"
          name="email"
          type="email"
          autoComplete="email"
          placeholder="you@company.com"
          value={email}
          onChange={(event) => setEmail(event.target.value)}
          leadingIcon={<Mail className="size-4" />}
          disabled={submitting}
          required
        />
      </Field>

      <Button
        type="submit"
        size="lg"
        className="w-full"
        loading={submitting}
        trailingIcon={<Send className="size-4" />}
      >
        Send reset link
      </Button>
    </form>
  );
}
